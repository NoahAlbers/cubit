const assert = require('assert/strict')
const { request } = require('./native-smoke.cjs')
require('ts-node/register')
const { AppDataSource } = require('../src/app')
const { Member } = require('../src/entity/member')
const { MemberPlan } = require('../src/entity/memberPlan')
const { Transaction } = require('../src/entity/transaction')
const { BillingChange } = require('../src/entity/billingChange')
const { AccessLog } = require('../src/entity/accessLog')
const { BillingCharge, ChargeAdjustment, OperationsAudit } = require('../src/entity/cubitOperations')
const { seedPlanCatalog } = require('../src/dev/seed-plan-catalog')
const { Plan } = require('../src/entity/plan')
const { seedScenarios } = require('../src/dev/seed-scenarios')
const { day } = require('../src/billing/ledger')
async function main() {
  assert.equal((await request('/api/cubit/members')).status, 401)
  assert.equal((await request('/member', { method: 'PUT', body: {} })).status, 401)
  assert.equal((await request('/login', { method: 'POST', body: { email: 'missing@example.test', password: 'wrong' } })).status, 401)
  const token = (await request('/login', { method: 'POST', body: { email: 'admin@example.test', password: 'LocalDemoOnly!2026' } })).json().token
  const memberToken = (await request('/login', { method: 'POST', body: { email: 'alex@example.test', password: 'LocalDemoOnly!2026' } })).json().token
  assert.equal((await request('/api/cubit/members', { token: memberToken })).status, 403)
  assert.equal((await request('/plan/memberplan', { token: memberToken, method: 'POST', body: {} })).status, 403)
  const get = async route => {
    const result = await request(route, { token })
    assert.equal(result.status, 200, result.text); return result.json()
  }
  const all = await get('/api/cubit/members?pageSize=100')
  assert.ok(all.total >= 75)
  assert.ok(all.rows.every(m => !('password' in m)))
  const match = async (q, field, expected) => {
    const data = await get('/api/cubit/members?' + new URLSearchParams({ q, field }))
    assert.ok(data.rows.some(m => m.email === expected), `Search failed: ${field} ${q}`)
  }
  await match('MORGAN RIVERA', 'all', 'morgan.rivera@example.test')
  await match('morgan.rivera@', 'email', 'morgan.rivera@example.test')
  await match('billing.1@', 'paypalEmail', 'morgan.rivera@example.test')
  await match('2025550100', 'phone', 'morgan.rivera@example.test')
  await match('river', 'lastName', 'morgan.rivera@example.test')
  const combined = await get('/api/cubit/members?q=Rivera&status=Active&activity=30')
  assert.ok(combined.total > 0 && combined.rows.every(m => m.status === 'Active' && m.lastKeyUsage))
  const never = await get('/api/cubit/members?activity=never&pageSize=100')
  assert.ok(never.total > 0 && never.rows.every(m => m.lastKeyUsage === null))
  const availablePlans = await get('/plan?available=true')
  assert.deepEqual(availablePlans.map(p => Number(p.monthlyCost)).sort((a,b) => a-b), [30,60,90,120,150])
  const overdue = await get('/api/cubit/members?overdue=true&sort=amount&pageSize=100')
  assert.ok(overdue.total > 0 && overdue.rows.every(m => m.pastDue > 0))
  assert.ok(overdue.rows.every((m, i, a) => !i || a[i-1].pastDue >= m.pastDue))
  const aged = await get('/api/cubit/members?overdue=true&sort=oldest&pageSize=100')
  assert.ok(aged.rows.every((m, i, a) => !i || a[i-1].daysPastDue >= m.daysPastDue))
  assert.ok(overdue.rows.every(m => m.status !== 'Canceled'))
  const withEnded = await get('/api/cubit/members?overdue=true&includeEnded=true&pageSize=100')
  assert.ok(withEnded.rows.some(m => m.status === 'Canceled'))
  const accessEnabled = await get('/api/cubit/members?overdue=true&access=enabled&pageSize=100')
  assert.ok(accessEnabled.total > 0 && accessEnabled.rows.every(m => m.accessAllowed))
  assert.equal(all.summary.uniqueCheckins30Days, all.rows.filter(m => m.checkedIn30Days).length)
  const second = await get('/api/cubit/members?page=2')
  const first = await get('/api/cubit/members?page=1')
  assert.ok(!second.rows.some(m => first.rows.some(n => n.id === m.id)))
  const missing = await get('/api/cubit/members?q=nonexistent-member-query')
  assert.equal(missing.total, 0)
  await AppDataSource.initialize()
  let id
  try {
    const count = await AppDataSource.manager.count(Member)
    await seedScenarios()
    assert.equal(await AppDataSource.manager.count(Member), count, 'Seeding must be idempotent')
    const catalogCount = await AppDataSource.manager.count(Plan)
    await seedPlanCatalog()
    assert.equal(await AppDataSource.manager.count(Plan), catalogCount)
    const created = await request('/member', { token, method: 'POST', body: {
      id: 'New', firstName: 'Integration', lastName: 'Fixture', email: `integration.${Date.now()}@example.test`, paypalEmail: '', password: '',
    } })
    assert.equal(created.status, 200, created.text); id = created.json().id
    const visitsBefore = (await get('/api/cubit/members')).summary.uniqueCheckins30Days
    const visit = (ageDays, accessGranted) => AppDataSource.manager.save(AccessLog,
      AppDataSource.manager.create(AccessLog, { member: { id }, timestamp: new Date(Date.now() - ageDays * 86400000), accessGranted, message: 'Temporary check-in test' }))
    await visit(1, false)
    await visit(31, true)
    await visit(-1, true)
    assert.equal((await get('/api/cubit/members')).summary.uniqueCheckins30Days, visitsBefore, 'Denied, old and future events are excluded')
    await visit(1, true)
    await visit(2, true)
    assert.equal((await get('/api/cubit/members')).summary.uniqueCheckins30Days, visitsBefore + 1, 'Repeat visits count as one unique member')
    const today = new Date(), start = day(new Date(today.getFullYear(), today.getMonth() - 3, 1)), cutoff = day(new Date(today.getFullYear(), today.getMonth() - 1, 1))
    const plan = await request('/plan/memberplan', { token, method: 'POST', body: {
      id: 'New', memberId: id, planId: '80000000-0000-4000-8000-000000000001', startDate: start,
    } })
    assert.equal(plan.status, 200, plan.text)
    const planId = plan.json().id
    const payment = await request('/transaction', { token, method: 'POST', body: { id: 'New', memberId: id,
      amount: 25.55, transactionDate: start, method: 'Local test', description: 'Temporary integration fixture', requestKey: require('crypto').randomUUID() } })
    assert.equal(payment.status, 200, payment.text)
    const before = await get(`/api/cubit/members/${id}/billing`)
    assert.equal(before.balance, 214.45, JSON.stringify({ plans: before.plans, charges: before.charges }))
    const payload = { finalBillingDate: cutoff, reason: 'Integration test cancellation', expectedDate: null }
    const preview = await request(`/api/cubit/plans/${planId}/cutoff`, { token, method: 'POST', body: { ...payload, preview: true } })
    assert.equal(preview.status, 200, preview.text)
    assert.equal(preview.json().after.balance, 154.45)
    assert.equal((await get(`/api/cubit/members/${id}/billing`)).balance, before.balance, 'Preview must not mutate')
    const invalid = await request(`/api/cubit/plans/${planId}/cutoff`, { token, method: 'POST', body: { ...payload, finalBillingDate: '1900-01-01' } })
    assert.equal(invalid.status, 400)
    const saved = await request(`/api/cubit/plans/${planId}/cutoff`, { token, method: 'POST', body: payload })
    assert.equal(saved.status, 200, saved.text)
    const after = await get(`/api/cubit/members/${id}/billing`)
    assert.equal(after.balance, 154.45)
    assert.equal(after.status, 'Canceled')
    assert.equal(after.history.length, 1)
    assert.equal(after.history[0].changedBy, 'admin@example.test')
    assert.ok(after.charges.every(c => c.dueDate <= cutoff))
    assert.equal((await get('/member/isActive/' + id)), false)
    assert.equal(await get('/member/balance/' + id), 154.45, 'Status checks must preserve cancellation debt')
    const conflict = await request(`/api/cubit/plans/${planId}/cutoff`, { token, method: 'POST', body: payload })
    assert.equal(conflict.status, 409)
    const duplicate = await request(`/api/cubit/plans/${planId}/cutoff`, { token, method: 'POST', body: { ...payload, expectedDate: cutoff } })
    assert.equal(duplicate.status, 200)
    assert.equal((await get(`/api/cubit/members/${id}/billing`)).history.length, 1)
    assert.equal((await request('/plan/memberplan', { token, method: 'POST', body: { ...plan.json(), endDate: null } })).status, 400)
  } finally {
    if (id) {
      await AppDataSource.manager.createQueryBuilder().delete().from(AccessLog).where('memberId = :id', { id }).execute()
      await AppDataSource.manager.delete(BillingChange, { memberId: id })
      await AppDataSource.manager.delete(ChargeAdjustment, { memberId: id })
      await AppDataSource.manager.delete(BillingCharge, { memberId: id })
      await AppDataSource.manager.delete(OperationsAudit, { memberId: id })
      await AppDataSource.manager.delete(Transaction, { memberId: id })
      await AppDataSource.manager.delete(MemberPlan, { memberId: id })
      await AppDataSource.manager.delete(Member, { id })
    }
    await AppDataSource.destroy()
  }
  console.log('PASS: staff permissions, combined search/filter/sort/pagination, fixtures, cutoff preview/save/audit/conflict, cents, cancellation debt, and legacy endpoint protections.')
}
main().catch(err => { console.error(err.message); process.exitCode = 1 })
