const assert = require('assert/strict')
require('ts-node/register')
const { billingLedger, anniversary, membershipStatus, validDay } = require('../src/billing/ledger')
const plan = (extra = {}) => ({ id: 'plan', startDate: '2026-01-31', plan: { name: 'Test', monthlyCost: 50 }, ...extra })
assert.equal(anniversary('2026-01-31', 1), '2026-02-28')
assert.equal(anniversary('2026-01-31', 2), '2026-03-31')
assert.equal(anniversary('2024-01-31', 1), '2024-02-29')
assert.equal(validDay('2026-02-30'), false)
assert.deepEqual(billingLedger([plan()], [], '2026-03-30').charges.map(c => c.dueDate), ['2026-01-31', '2026-02-28'])
assert.equal(billingLedger([plan({ startDate: '2027-01-01' })], [], '2026-09-22').balance, 0)
assert.equal(billingLedger([plan({ endDate: '2027-01-01' })], [], '2026-02-01').totalCharges, 50, 'Future end dates must not charge in advance')
const ended = plan({ finalBillingDate: '2026-02-28' })
const feb = billingLedger([ended], [{ amount: 25.25, transactionDate: '2026-02-01' }], '2026-03-01')
const later = billingLedger([ended], [{ amount: 25.25, transactionDate: '2026-02-01' }], '2028-03-01')
assert.equal(feb.balance, 74.75)
assert.equal(later.balance, feb.balance, 'Canceled dues never grow after the cutoff')
assert.equal(feb.charges[0].outstanding, 24.75)
assert.equal(feb.pastDue, 74.75)
assert.equal(feb.oldestUnpaidDate, '2026-01-31')
assert.equal(feb.daysPastDue, 29)
assert.equal(membershipStatus([ended], later.balance, '2028-03-01'), 'Canceled')
assert.equal(billingLedger([ended], [{ amount: 100, transactionDate: '2026-02-01' }], '2028-03-01').pastDue, 0)
assert.equal(billingLedger([ended], [{ amount: 150, transactionDate: '2026-02-01' }], '2028-03-01').credit, 50)
assert.equal(billingLedger([ended], [{ amount: 150, transactionDate: '2029-02-01' }], '2028-03-01').totalPaid, 0)
assert.equal(billingLedger([plan()], [], '2026-01-31').pastDue, 0, 'Due today is not past due')
assert.equal(billingLedger([plan()], [], '2026-02-01').pastDue, 50)
assert.equal(billingLedger([plan({ endDate: '2026-02-15' })], [], '2026-09-01').totalCharges, 50)
assert.equal(billingLedger([plan({ plan: { name: 'Cents', monthlyCost: 12.35 } })], [{ amount: 10.10, transactionDate: '2026-01-31' }], '2026-02-01').balance, 2.25)
const refund = billingLedger([ended], [{ amount: 100, transactionDate: '2026-02-01' }, { amount: -25, transactionDate: '2026-02-15' }], '2026-03-01')
assert.equal(refund.balance, 25)
assert.equal(refund.oldestUnpaidDate, '2026-02-28')
console.log('PASS: inclusive cutoffs, future plans/end dates/payments, month-end/leap anniversaries, partial payments, credit, refunds, aging and cents.')
