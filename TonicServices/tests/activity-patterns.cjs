require('ts-node/register')
const assert=require('assert/strict')
const {localAccessEntries,busiestTimes}=require('../src/billing/activity-patterns')
const event=(timestamp,accessGranted=true)=>({timestamp,accessGranted})
const logs=[event('2026-07-01T03:59:00Z'),event('2026-07-01T04:00:00Z'),event('2026-07-02T03:59:00Z'),event('2026-07-02T04:00:00Z'),event('2026-07-01T12:00:00Z',false),event('bad')]
const entries=localAccessEntries(logs,'2026-07-01','2026-07-01',new Date('2026-07-02T12:00:00Z'))
assert.equal(entries.length,3)
const heat=busiestTimes(entries,'2026-07-01','2026-07-01')
assert.equal(heat.total,2);assert.equal(heat.weekHours[2].values[0],1);assert.equal(heat.weekHours[2].values[23],1)
assert.equal(heat.monthDays[0].values[0],2);assert.equal(heat.monthDays[0].values[1],null)
const fallback=localAccessEntries([event('2026-11-01T05:30:00Z'),event('2026-11-01T06:30:00Z')],'2026-11-01','2026-11-01',new Date('2026-11-02T12:00:00Z'))
assert.deepEqual(fallback.map(e=>e.hour),[1,1]);assert.equal(busiestTimes(fallback,'2026-11-01','2026-11-01').weekHours[6].values[1],2)
const spring=localAccessEntries([event('2026-03-08T06:30:00Z'),event('2026-03-08T07:30:00Z')],'2026-03-08','2026-03-08',new Date('2026-03-09T12:00:00Z'))
assert.deepEqual(spring.map(e=>e.hour),[1,3])
const leap=busiestTimes([],'2024-02-01','2024-03-02')
assert.equal(leap.monthDays[0].values[28],0);assert.equal(leap.monthDays[0].values[29],null);assert.equal(leap.monthDays[1].values[2],null)
assert.equal(localAccessEntries([event('2026-07-01T15:00:00Z')],'2026-07-01','2026-07-01',new Date('2026-07-01T14:00:00Z')).length,0)
assert.equal(heat.weekHours.flatMap(r=>r.values).reduce((a,b)=>a+b,0),heat.total)
assert.equal(heat.monthDays.flatMap(r=>r.values).reduce((a,b)=>a+(b||0),0),heat.total)
console.log('PASS: local calendar boundaries, denied/future/invalid events, DST transitions, partial periods, leap dates and matching heatmap totals.')
